import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import type { InitializedConfig } from '../project/config.js';
import type { ProjectPaths } from '../project/paths.js';
import { hostOf, isLoopbackHost } from '../project/site-url.js';

const TEMPLATES_DIR = fileURLToPath(new URL('../../templates/', import.meta.url));
const DOCKER_TEMPLATES = ['Dockerfile', 'local-entrypoint.sh', 'mailpit.php'];

const WP_ROOT = '/var/www/html';
const WP_CONTENT = `${WP_ROOT}/wp-content`;

interface ComposeService {
  image: string;
  build?: { context: string; args: Record<string, string> };
  command?: string[];
  ports?: string[];
  environment?: Record<string, string>;
  volumes?: string[];
  extra_hosts?: string[];
  depends_on?: Record<string, { condition: 'service_healthy' }>;
  healthcheck?: { test: string[]; interval: string; timeout: string; retries: number; start_period: string };
}

export interface ComposeFile {
  name: string;
  services: Record<'wordpress' | 'database' | 'mailpit', ComposeService>;
  volumes: Record<string, object>;
}

export function buildComposeFile(config: InitializedConfig): ComposeFile {
  return {
    name: `wpbox-${config.project}`,
    services: {
      wordpress: wordpressService(config),
      database: databaseService(config),
      mailpit: mailpitService(config),
    },
    volumes: { wordpress_data: {}, database_data: {} },
  };
}

export function writeComposeProject(paths: ProjectPaths, config: InitializedConfig): void {
  copyDockerTemplates(paths.dockerContext);
  createMountedFolders(paths, config);

  const header = '# Generated by wpbox from .wpbox/config.json. Run `wpbox init` to change it.\n';
  fs.writeFileSync(paths.compose, header + YAML.stringify(buildComposeFile(config)));
}

function wordpressService(config: InitializedConfig): ComposeService {
  const host = hostOf(config.local.url);

  return {
    build: { context: './docker', args: { WORDPRESS_TAG: config.wordpressImage } },
    image: `wpbox-wordpress:${config.wordpressImage}`,
    ports: [`127.0.0.1:${config.local.port}:80`],
    environment: {
      WORDPRESS_DB_HOST: 'database:3306',
      WORDPRESS_DB_NAME: config.database.name,
      WORDPRESS_DB_USER: config.database.user,
      WORDPRESS_DB_PASSWORD: config.database.password,
      WORDPRESS_TABLE_PREFIX: config.production.tablePrefix,
      WORDPRESS_DEBUG: '1',
      WORDPRESS_CONFIG_EXTRA: wordpressConstants(),
      SITE_URL: config.local.url,
      LOCAL_PORT: String(config.local.port),
      WP_CLI_CACHE_DIR: '/tmp/wp-cli-cache',
    },
    volumes: [
      `wordpress_data:${WP_ROOT}`,
      `../src/uploads:${WP_CONTENT}/uploads`,
      ...config.devCode.themes.map((theme) => `../src/themes/${theme}:${WP_CONTENT}/themes/${theme}`),
      ...config.devCode.plugins.map((plugin) => `../src/plugins/${plugin}:${WP_CONTENT}/plugins/${plugin}`),
      `./docker/mailpit.php:${WP_CONTENT}/mu-plugins/wpbox-mailpit.php:ro`,
      './:/wpbox:ro',
    ],
    extra_hosts: isLoopbackHost(host) ? undefined : [`${host}:127.0.0.1`],
    depends_on: { database: { condition: 'service_healthy' } },
  };
}

function wordpressConstants(): string {
  return [
    "define('WP_ENVIRONMENT_TYPE', 'local');",
    "define('WP_DEVELOPMENT_MODE', 'all');",
    "define('WP_HOME', getenv_docker('SITE_URL', ''));",
    "define('WP_SITEURL', getenv_docker('SITE_URL', ''));",
    "define('WP_DEBUG_LOG', true);",
    "define('WP_DEBUG_DISPLAY', true);",
  ].join('\n');
}

function databaseService(config: InitializedConfig): ComposeService {
  return {
    image: 'mariadb:11.4',
    command: ['--max-allowed-packet=1G'],
    environment: {
      MARIADB_DATABASE: config.database.name,
      MARIADB_USER: config.database.user,
      MARIADB_PASSWORD: config.database.password,
      MARIADB_ROOT_PASSWORD: config.database.rootPassword,
    },
    volumes: ['database_data:/var/lib/mysql', './:/wpbox', '../dumps:/dumps'],
    healthcheck: {
      test: ['CMD', 'healthcheck.sh', '--connect', '--innodb_initialized'],
      interval: '5s',
      timeout: '5s',
      retries: 30,
      start_period: '30s',
    },
  };
}

function mailpitService(config: InitializedConfig): ComposeService {
  return {
    image: 'axllent/mailpit:v1.21',
    ports: [`127.0.0.1:${config.local.mailpitPort}:8025`],
  };
}

function copyDockerTemplates(target: string): void {
  fs.mkdirSync(target, { recursive: true });
  for (const file of DOCKER_TEMPLATES) {
    const content = fs.readFileSync(path.join(TEMPLATES_DIR, file), 'utf8').replace(/\r\n/g, '\n');
    fs.writeFileSync(path.join(target, file), content);
  }
}

function createMountedFolders(paths: ProjectPaths, config: InitializedConfig): void {
  const folders = [
    paths.srcUploads,
    paths.dumps,
    paths.stage,
    ...config.devCode.themes.map((theme) => path.join(paths.srcThemes, theme)),
    ...config.devCode.plugins.map((plugin) => path.join(paths.srcPlugins, plugin)),
  ];
  for (const folder of folders) fs.mkdirSync(folder, { recursive: true });
}
